import argparse
import csv
from pathlib import Path


VERSION = "v1.0"


DECISION_VALUES = [
    "pending",
    "accept_as_is",
    "replace",
    "add_to_dictionary",
    "add_to_whitelist",
    "add_to_known_pattern",
    "ignore_noise",
]


def parse_suspicious_line(line: str):
    """
    Example:
    бТоболуьйтург | reason: suspicious pair 'бТ' | candidates: бтоболуьйтург

    Returns:
    word, reason, candidates
    """
    parts = [part.strip() for part in line.split("|")]

    if len(parts) < 2:
        return None

    word = parts[0].strip()
    reason = ""
    candidates = ""

    for part in parts[1:]:
        if part.startswith("reason:"):
            reason = part.replace("reason:", "", 1).strip()
        elif part.startswith("candidates:"):
            candidates = part.replace("candidates:", "", 1).strip()

    if not word or not reason:
        return None

    return word, reason, candidates


def load_suspicious_entries(path: Path):
    if not path.exists():
        raise FileNotFoundError(f"Suspicious report not found: {path}")

    lines = path.read_text(encoding="utf-8", errors="replace").splitlines()

    entries = []
    seen = set()

    for line in lines:
        parsed = parse_suspicious_line(line)

        if not parsed:
            continue

        word, reason, candidates = parsed
        key = (word, reason, candidates)

        if key in seen:
            continue

        seen.add(key)

        entries.append({
            "word": word,
            "reason": reason,
            "candidates": candidates,
        })

    return entries


def reason_priority(reason: str) -> int:
    """
    Sort order for review.

    We want concrete palochka-like patterns first,
    then suspicious symbols,
    then uppercase-inside-word.
    """
    if "known OCR pattern" in reason:
        return 0

    if "suspicious pair" in reason:
        return 1

    if "contains suspicious OCR char" in reason:
        return 2

    if "uppercase letter inside word" in reason:
        return 3

    return 9


def write_review_csv(entries, output_csv: Path):
    output_csv.parent.mkdir(parents=True, exist_ok=True)

    sorted_entries = sorted(
        entries,
        key=lambda item: (
            reason_priority(item["reason"]),
            item["reason"],
            item["word"].lower(),
        )
    )

    fieldnames = [
        "id",
        "word",
        "reason",
        "candidates",
        "decision",
        "replacement",
        "notes",
    ]

    with output_csv.open("w", encoding="utf-8-sig", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=fieldnames)
        writer.writeheader()

        for index, item in enumerate(sorted_entries, start=1):
            candidates = item["candidates"]

            suggested_replacement = ""
            if candidates and candidates != "none" and "," not in candidates:
                suggested_replacement = candidates

            writer.writerow({
                "id": index,
                "word": item["word"],
                "reason": item["reason"],
                "candidates": candidates,
                "decision": "pending",
                "replacement": suggested_replacement,
                "notes": "",
            })


def write_readme(output_path: Path):
    text = f"""Suspicious review table
=======================

Generated by make_review_table.py {VERSION}

Open suspicious_review_table.csv in Excel.

Columns:
- id: row number
- word: suspicious OCR token
- reason: why processor marked it suspicious
- candidates: possible candidate corrections
- decision: your manual decision
- replacement: corrected form if decision is replace/add_to_known_pattern
- notes: optional comments

Allowed decision values:
{chr(10).join("- " + value for value in DECISION_VALUES)}

Recommended workflow:
1. Start with rows where reason contains "suspicious pair".
2. Then review rows with "[" or "]" or "!" or "1".
3. Leave difficult "uppercase letter inside word" rows as pending if unsure.
4. Do not guess Chechen forms. If unsure, keep pending.

Decision meanings:
- pending: not reviewed yet
- accept_as_is: word is correct; no processor change needed
- replace: this exact token should be replaced with replacement
- add_to_dictionary: corrected form should be added to palochka dictionary
- add_to_whitelist: word should never be marked suspicious
- add_to_known_pattern: add word -> replacement to KNOWN_SUSPICIOUS_CANDIDATES
- ignore_noise: OCR garbage or page artifact; do not use for language rules
"""

    output_path.write_text(text, encoding="utf-8")


def main():
    parser = argparse.ArgumentParser(
        description="Create manual review CSV table from suspicious report"
    )

    parser.add_argument(
        "--suspicious",
        required=True,
        help="Path to *_suspicious.txt"
    )

    parser.add_argument(
        "--output-dir",
        default="output/review",
        help="Output directory"
    )

    args = parser.parse_args()

    suspicious_path = Path(args.suspicious)
    output_dir = Path(args.output_dir)

    entries = load_suspicious_entries(suspicious_path)

    output_csv = output_dir / "suspicious_review_table.csv"
    output_readme = output_dir / "suspicious_review_readme.txt"

    write_review_csv(entries, output_csv)
    write_readme(output_readme)

    print(f"make_review_table.py version: {VERSION}")
    print(f"Suspicious input: {suspicious_path}")
    print(f"Entries loaded: {len(entries)}")
    print(f"Review CSV saved: {output_csv}")
    print(f"Readme saved: {output_readme}")


if __name__ == "__main__":
    main()