def test_detect_suspicious_words_deduplicates(ctx_factory, tiny_dictionaries):
    ctx = ctx_factory(tiny_dictionaries)
    text = "до[учу текст до[учу дела"
    found = detect_suspicious_words(text, ctx)
    assert len(found) == 1
    assert found[0].word == "до[учу"


