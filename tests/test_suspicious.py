def test_candidate_verified_in_dictionary_is_suggested(ctx_factory, tiny_dictionaries):
    # "хТара" -> "хӀара" is generated by the pair-substitution logic
    # AND "хӀара" is in tiny_dictionaries' palochka_words -- the
    # ordinary, fully-verified case. The word also happens to trigger
    # the mid-word-capital case fallback ("хтара"), which is fine --
    # the verified pattern candidate must simply come first.
    ctx = ctx_factory(tiny_dictionaries)
    candidates = get_suspicious_candidates("хТара", ctx)
    assert candidates[0] == "хӀара"


def test_unverified_generated_candidate_is_still_suggested():
    # Found via real-world usage: a real word like "бӀаьхоша" is a
    # correctly-generated candidate (single pattern substitution) but
    # can easily be missing from a general ~80k-word dictionary as a
    # specific inflected form. Unlike auto-correction
    # (SingleCandidateDictionaryFix), the human-facing suggestion list
    # must still surface it -- hiding the most likely correct answer
    # and showing only a decoy (case-fix) candidate actively hurts
    # review, since a person judges correctness visually anyway.
    from chechen_ocr.config import Settings
    from chechen_ocr.core import PipelineContext
    from chechen_ocr.dictionaries import Dictionaries

    # Empty palochka_words -- "бӀаьхоша" is NOT verified in any dictionary.
    ctx = PipelineContext(settings=Settings.default(), dictionaries=Dictionaries.empty())

    candidates = get_suspicious_candidates("бТаьхоша", ctx)

    assert "бӀаьхоша" in candidates


def test_verified_candidate_is_ranked_before_unverified_ones():
    from chechen_ocr.config import Settings
    from chechen_ocr.core import PipelineContext
    from chechen_ocr.dictionaries import Dictionaries

    # "к1а]н" generates two candidates: "кӀа]н" (via '1'->Ӏ) and
    # "к1аӀн" (via ']'->Ӏ) -- only the first is "verified" here.
    # NOTE: .lower() is required here -- Ӏ (U+04C0) lowercases to a
    # DIFFERENT codepoint (U+04CF), which is what membership checks
    # compare against (see tests/conftest.py for the full explanation).
    dictionaries = Dictionaries(palochka_words=frozenset({"кӀа]н".lower()}))
    ctx = PipelineContext(settings=Settings.default(), dictionaries=dictionaries)

    candidates = get_suspicious_candidates("к1а]н", ctx)

    assert candidates[0] == "кӀа]н"
    assert "к1аӀн" in candidates[1:]


def test_case_only_fallback_still_included_after_pattern_candidates():
    from chechen_ocr.config import Settings
    from chechen_ocr.core import PipelineContext
    from chechen_ocr.dictionaries import Dictionaries

    # "кТоргех" has both a pattern-generated candidate ("кӀоргех", via
    # 'Т'->'Ӏ' pair substitution) and a mid-word-capital case fix
    # ("кторгех") -- the pattern candidate should be listed first.
    ctx = PipelineContext(settings=Settings.default(), dictionaries=Dictionaries.empty())

    candidates = get_suspicious_candidates("кТоргех", ctx)

    assert candidates[0] == "кӀоргех"
    assert "кторгех" in candidates


def test_known_suspicious_candidates_take_priority_over_generated_ones():
    from chechen_ocr.config import Settings
    from chechen_ocr.core import PipelineContext
    from chechen_ocr.dictionaries import Dictionaries

    dictionaries = Dictionaries(known_suspicious_candidates={"хТара": ("некий_особый_случай",)})
    ctx = PipelineContext(settings=Settings.default(), dictionaries=dictionaries)

    candidates = get_suspicious_candidates("хТара", ctx)

    assert candidates == ["некий_особый_случай"]
