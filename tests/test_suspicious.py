from chechen_ocr.suspicious import (
    detect_suspicious_words,
    get_suspicious_candidates,
    is_suspicious_word,
)


def test_dictionary_word_is_not_suspicious(ctx_factory, tiny_dictionaries):
    ctx = ctx_factory(tiny_dictionaries)
    is_bad, reason = is_suspicious_word("хӀара", ctx)
    assert is_bad is False


def test_word_with_bracket_is_suspicious(ctx_factory, tiny_dictionaries):
    ctx = ctx_factory(tiny_dictionaries)
    is_bad, reason = is_suspicious_word("до[учу", ctx)
    assert is_bad is True
    assert "suspicious OCR char" in reason


def test_whitelisted_word_is_not_suspicious(ctx_factory, tiny_dictionaries):
    ctx = ctx_factory(tiny_dictionaries)
    is_bad, _ = is_suspicious_word("Маьлха-Аьзни", ctx)
    assert is_bad is False


def test_whitelist_suppresses_a_word_that_would_otherwise_be_flagged(ctx_factory):
    from chechen_ocr.dictionaries import Dictionaries

    # "тест1слово" contains a suspicious char ('1') and would normally
    # be flagged -- unless it's on the whitelist.
    dictionaries = Dictionaries(suspicious_whitelist=frozenset({"тест1слово"}))
    ctx = ctx_factory(dictionaries)

    is_bad, _ = is_suspicious_word("тест1слово", ctx)
    assert is_bad is False

    # Sanity check: the same word without the whitelist entry IS flagged.
    ctx_no_whitelist = ctx_factory(Dictionaries())
    is_bad_unlisted, reason = is_suspicious_word("тест1слово", ctx_no_whitelist)
    assert is_bad_unlisted is True


